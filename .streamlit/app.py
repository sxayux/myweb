# =================================================================
import streamlit as st

# -----------------------------------------------------------------
# 1️⃣ [Header Zone] 웹 화면 메인 간판 및 설명
# -----------------------------------------------------------------
st.title("🍕 시험 기간 맞춤 큐레이터 '야식요정'")
st.caption("※ 밤 10시 이후, 당신의 기분과 칼로리 상태에 따라 딱 맞는 야식을 추천합니다.")

# -----------------------------------------------------------------
# 2️⃣ [Left Sidebar] 좌측 사이드바: 개인 설정 및 상태 선택
# -----------------------------------------------------------------
with st.sidebar:
    st.header("⚙️ 내 정보 설정")
    user_name = st.text_input("사용자 별명:", placeholder="예: 김인공")
    mood = st.selectbox(
        "오늘의 기분 상태를 선택하세요:",
        ["😊 행복함", "😭 우울함", "🤯 스트레스 받음", "🥱 피곤함"]
    )
    st.caption("💡 팁: 내 상태를 정확히 선택할수록 AI가 딱 맞는 조언을 해줍니다.")

# -----------------------------------------------------------------
# 3️⃣ [Main Input Zone] 메인 화면: 구체적인 고민 작성
# -----------------------------------------------------------------
st.subheader("📝 현재 고민이나 상황을 들려주세요")
user_story = st.text_area(
    "어떤 상황인가요? 자유롭게 적어주세요:",
    placeholder="예: 내일 수학 시험인데 잠 깨는 매콤한 게 당겨!"
)

# -----------------------------------------------------------------
# 4️⃣ [Action & Output Zone] 실행 버튼 및 2단 결과 출력
# -----------------------------------------------------------------
if st.button("✨ AI 맞춤 추천받기"):
    # 입력값이 비어있지 않은지 검증 (UX 예외 처리)
    if user_story:
        # 로딩 애니메이션 모래시계
        with st.spinner(f"AI가 {user_name if user_name else '사용자'}님의 고민을 바탕으로 야식을 고르는 중입니다... 🤖"):
            
            # 2단 칼럼 레이아웃으로 결과 분할 출력 (st.columns)
            col1, col2 = st.columns(2)
            
            with col1:
                st.success("🎉 AI 추천 야식")
                st.write("👉 **매콤한 떡볶이 & 쿨피스**")
                
            with col2:
                st.info("💡 칼로리 섭취 꿀팁")
                st.write("👉 국물 소스는 조금만 찍어 드시고 물을 자주 드세요!")
    else:
        # 빈 입력창일 때 경고 상자
        st.warning("⚠️ 고민 내용을 먼저 작성해 주세요!")
        st.info("💡 칼로리 섭취 꿀팁")
        st.write("👉 국물 소스는 조금만 찍어 드시고 물을 자주 드세요!")
